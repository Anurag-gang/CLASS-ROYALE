export async function seedQuizLevels() {
  console.log("Seeding 7-Level Knowledge Kingdom Architecture across all 6 subjects...");

  for (const [slug, def] of Object.entries(REALM_LEVEL_DEFINITIONS)) {
    const subject = await prisma.territorySubject.findUnique({
      where: { slug },
    });

    for (const lvl of def.levels) {
      await prisma.quizLevel.upsert({
        where: {
          subjectSlug_levelNumber: {
            subjectSlug: slug,
            levelNumber: lvl.levelNumber,
          },
        },
        update: {
          title: lvl.title,
          subtitle: lvl.subtitle,
          purpose: lvl.purpose,
          difficulty: lvl.difficulty,
          passingThreshold: lvl.passingThreshold,
          totalQuestions: lvl.totalQuestions,
          allowHints: lvl.allowHints,
          xpReward: lvl.xpReward,
          subjectId: subject ? subject.id : undefined,
        },
        create: {
          subjectSlug: slug,
          levelNumber: lvl.levelNumber,
          title: lvl.title,
          subtitle: lvl.subtitle,
          purpose: lvl.purpose,
          difficulty: lvl.difficulty,
          passingThreshold: lvl.passingThreshold,
          totalQuestions: lvl.totalQuestions,
          allowHints: lvl.allowHints,
          xpReward: lvl.xpReward,
          subjectId: subject ? subject.id : undefined,
          status: "ACTIVE",
        },
      });
    }
  }

  // Ensure all existing students have Level 1 unlocked by default
  const students = await prisma.user.findMany({ where: { role: "STUDENT" } });
  console.log(`Setting up Level 1 default unlocks for ${students.length} students...`);

  for (const student of students) {
    for (const slug of Object.keys(REALM_LEVEL_DEFINITIONS)) {
      await prisma.studentLevelProgress.upsert({
        where: {
          userId_subjectSlug_levelNumber: {
            userId: student.id,
            subjectSlug: slug,
            levelNumber: 1,
          },
        },
        update: {
          isUnlocked: true,
        },
        create: {
          userId: student.id,
          subjectSlug: slug,
          levelNumber: 1,
          isUnlocked: true,
        },
      });
    }
  }

  console.log("✔ 7-Level Architecture seeded successfully!");
  await prisma.$disconnect();
}

if (require.main === module) {
  seedQuizLevels().catch(console.error);
}
