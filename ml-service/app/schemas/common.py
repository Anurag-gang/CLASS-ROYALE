"""
Common Enums, Base Models, and Feature Type Classifications for Class Royale ML
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class FeatureType(str, Enum):
    """
    Explicit feature role classification to prevent target leakage and document lineage.
    """
    RAW = "RAW"              # Directly captured student/system telemetry
    DERIVED = "DERIVED"      # Deterministically calculated from historical telemetry
    OPTIONAL = "OPTIONAL"    # Field may be absent across heterogeneous educational datasets
    TARGET = "TARGET"        # Target label to predict — NEVER use as input in feature vectors


class PredictionStatus(str, Enum):
    """Status indicator for model inference execution."""
    SUCCESS = "SUCCESS"
    MODEL_NOT_TRAINED = "MODEL_NOT_TRAINED"
    DEMO_DATA = "DEMO_DATA"
    FALLBACK_BASELINE = "FALLBACK_BASELINE"
    INSUFFICIENT_DATA = "INSUFFICIENT_DATA"
    ERROR = "ERROR"


class DifficultyLevel(str, Enum):
    """Categorical question difficulty bands derived from probability."""
    EASY = "EASY"        # P(correct) >= 0.75
    MEDIUM = "MEDIUM"    # 0.40 <= P(correct) < 0.75
    HARD = "HARD"        # P(correct) < 0.40


class TopicStatus(str, Enum):
    """Pedagogical mastery status of a student for an engineering topic."""
    STRONG = "STRONG"    # Mastery >= 0.75
    NORMAL = "NORMAL"    # 0.50 <= Mastery < 0.75
    WEAK = "WEAK"        # Mastery < 0.50 (Requires targeted intervention)


class LearningAction(str, Enum):
    """
    Deterministic adaptive learning decisions generated by the AdaptiveLearningEngine.
    """
    ANSWER_NEXT_QUESTION = "ANSWER_NEXT_QUESTION"
    REVISE_TOPIC = "REVISE_TOPIC"
    LOWER_DIFFICULTY = "LOWER_DIFFICULTY"
    INCREASE_DIFFICULTY = "INCREASE_DIFFICULTY"
    PRACTICE_WEAK_TOPIC = "PRACTICE_WEAK_TOPIC"
    REVIEW_CONCEPT = "REVIEW_CONCEPT"
    TAKE_BREAK = "TAKE_BREAK"


class ModelMetadata(BaseModel):
    """Lightweight metadata descriptor for registered models."""
    model_name: str
    model_version: str
    algorithm: str
    is_trained: bool = False
    feature_schema_version: str = "v1.0"
    training_timestamp: Optional[str] = None
    description: Optional[str] = None
    hyperparameters: Dict[str, Any] = Field(default_factory=dict)
    validation_metrics: Dict[str, Any] = Field(default_factory=dict)
    test_metrics: Dict[str, Any] = Field(default_factory=dict)


class BaseMLResponse(BaseModel):
    """Base response contract with status and auditability flags."""
    status: PredictionStatus = PredictionStatus.SUCCESS
    message: Optional[str] = None
    is_demo: bool = False
    model_version: Optional[str] = None
